//! Parsing of makemkvcon "robot" (-r) output. Robot mode prints lines like
//!
//! ```text
//! DRV:index,visible,enabled,flags,"drive name","disc name","device path"
//! CINFO:attr_id,code,"value"
//! TINFO:title_index,attr_id,code,"value"
//! MSG:code,flags,count,"message","format",params...
//! PRGV:current,total,max
//! PRGT/PRGC:code,id,"name"
//! ```
//!
//! Attribute ids were checked against real MakeMKV 2.0.0 output (see
//! tests/fixtures): CINFO 1 = disc type, 2 = disc name; TINFO 2 = title
//! name, 8 = chapter count, 9 = duration "H:MM:SS", 11 = size in bytes,
//! 16 = source file (e.g. 00800.mpls on Blu-ray).

use regex::Regex;
use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;
use std::sync::LazyLock;

/// Splits the part after `KIND:` into fields. Quoted fields may contain
/// commas and backslash escapes.
pub fn split_fields(text: &str) -> Vec<String> {
    let chars: Vec<char> = text.chars().collect();
    let n = chars.len();
    let mut fields = Vec::new();
    let mut i = 0;
    while i < n {
        if chars[i] == '"' {
            i += 1;
            let mut buf = String::new();
            while i < n && chars[i] != '"' {
                if chars[i] == '\\' && i + 1 < n {
                    buf.push(chars[i + 1]);
                    i += 2;
                } else {
                    buf.push(chars[i]);
                    i += 1;
                }
            }
            i += 1; // closing quote
            fields.push(buf);
            if i < n && chars[i] == ',' {
                i += 1;
            }
        } else {
            let start = i;
            while i < n && chars[i] != ',' {
                i += 1;
            }
            fields.push(chars[start..i].iter().collect());
            if i < n && chars[i] == ',' {
                i += 1;
            }
        }
    }
    fields
}

/// `("TINFO", fields)` for a robot line, None for anything else.
pub fn parse_line(line: &str) -> Option<(String, Vec<String>)> {
    let line = line.trim_end_matches(['\r', '\n']);
    let (kind, rest) = line.split_once(':')?;
    if kind.is_empty() || !kind.bytes().all(|b| b.is_ascii_uppercase()) {
        return None;
    }
    Some((kind.to_string(), split_fields(rest)))
}

/// The human-readable text of a MSG line.
pub fn msg_text(fields: &[String]) -> String {
    if fields.len() >= 4 {
        fields[3].clone()
    } else {
        fields.join(" ")
    }
}

#[derive(Debug, Clone, Serialize, PartialEq)]
pub struct DriveInfo {
    pub index: i32,
    pub drive_name: String,
    pub disc_name: String,
    pub has_disc: bool,
    pub device: String,
}

/// Every drive in an `info disc:9999` listing. MakeMKV always prints 16
/// slots; the unused ones have neither a name nor a device and are skipped.
pub fn parse_drives(out: &str) -> Vec<DriveInfo> {
    let mut drives = Vec::new();
    for line in out.lines() {
        let Some((kind, f)) = parse_line(line) else { continue };
        if kind != "DRV" {
            continue;
        }
        let Some(index) = f.first().and_then(|s| s.trim().parse::<i32>().ok()) else { continue };
        let get = |i: usize| f.get(i).cloned().unwrap_or_default();
        let (drive_name, disc_name, device) = (get(4), get(5), get(6));
        if drive_name.trim().is_empty() && device.trim().is_empty() {
            continue;
        }
        drives.push(DriveInfo {
            index,
            has_disc: !disc_name.trim().is_empty(),
            drive_name,
            disc_name,
            device,
        });
    }
    drives.sort_by_key(|d| d.index);
    drives
}

/// "MakeMKV v2.0.0 linux(x64-release)" from the "started" message (code 1005).
pub fn version_from_output(out: &str) -> Option<String> {
    out.lines().find_map(|line| {
        let (kind, f) = parse_line(line)?;
        (kind == "MSG" && f.len() >= 6 && f[0].trim() == "1005").then(|| f[5].clone())
    })
}

#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct Title {
    pub title_index: i64,
    pub duration_text: String,
    pub duration_sec: i64,
    pub chapters: i64,
    pub size_bytes: i64,
    pub source_file: String,
    pub name: String,
}

impl Title {
    /// Text that may contain an episode marker. Only the real title name:
    /// other text attributes are generated by MakeMKV (output file name,
    /// source codes like "E4") and produced a false "Episode 4" on a real disc.
    pub fn text_values(&self) -> Vec<String> {
        static LETTERS: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"[A-Za-z]{2,}").unwrap());
        if LETTERS.is_match(&self.name) {
            vec![self.name.clone()]
        } else {
            vec![]
        }
    }
}

#[derive(Debug, Clone, Default)]
pub struct Disc {
    pub disc_type: String,
    pub disc_name: String,
    pub titles: Vec<Title>,
    pub messages: Vec<String>,
}

static DURATION: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"^\d{1,2}:[0-5]\d:[0-5]\d$").unwrap());

fn hms_to_sec(text: &str) -> i64 {
    let parts: Vec<i64> = text.split(':').filter_map(|p| p.parse().ok()).collect();
    match parts.as_slice() {
        [h, m, s] => h * 3600 + m * 60 + s,
        _ => 0,
    }
}

pub fn parse_disc_info(out: &str) -> Disc {
    let mut disc = Disc::default();
    // title index -> attributes in the order they were printed (first one wins)
    let mut attrs: BTreeMap<i64, Vec<(i64, String)>> = BTreeMap::new();
    for line in out.lines() {
        let Some((kind, f)) = parse_line(line) else { continue };
        match kind.as_str() {
            "TINFO" if f.len() >= 4 => {
                let Ok(t) = f[0].trim().parse::<i64>() else { continue };
                if t < 0 {
                    continue;
                }
                let attr = f[1].trim().parse::<i64>().unwrap_or(-1);
                let entry = attrs.entry(t).or_default();
                if !entry.iter().any(|(a, _)| *a == attr) {
                    entry.push((attr, f[f.len() - 1].clone()));
                }
            }
            "CINFO" if f.len() >= 3 => match f[0].trim().parse::<i64>().unwrap_or(-1) {
                1 => disc.disc_type = f[f.len() - 1].clone(),
                2 => disc.disc_name = f[f.len() - 1].clone(),
                _ => {}
            },
            "MSG" => disc.messages.push(msg_text(&f)),
            _ => {}
        }
    }

    for (t, a) in attrs {
        let get = |id: i64| a.iter().find(|(k, _)| *k == id).map(|(_, v)| v.clone());
        let mut duration_text = get(9).unwrap_or_default();
        if !DURATION.is_match(&duration_text) {
            duration_text = a
                .iter()
                .map(|(_, v)| v)
                .find(|v| DURATION.is_match(v))
                .cloned()
                .unwrap_or_default();
        }
        let duration_sec = hms_to_sec(&duration_text);
        let to_int = |id: i64| get(id).and_then(|v| v.trim().parse::<i64>().ok()).unwrap_or(0);
        disc.titles.push(Title {
            title_index: t,
            duration_text: if duration_text.is_empty() { "0:00:00".into() } else { duration_text },
            duration_sec,
            chapters: to_int(8),
            size_bytes: to_int(11),
            source_file: get(16).unwrap_or_default(),
            name: get(2).unwrap_or_default(),
        });
    }
    disc
}

/// PRGV:current,total,max -> overall percent (0-100) of the running task.
pub fn parse_progress(fields: &[String]) -> Option<f64> {
    let total: f64 = fields.get(1)?.trim().parse().ok()?;
    let max: f64 = fields.get(2)?.trim().parse().ok()?;
    if max <= 0.0 {
        return None;
    }
    Some((total / max * 100.0).clamp(0.0, 100.0))
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct Hint {
    pub episode: i64,
    pub source: String,
    pub confidence: String,
}

static HINT_PATTERNS: LazyLock<Vec<(Regex, &'static str)>> = LazyLock::new(|| {
    vec![
        (Regex::new(r"(?i)\bepisode\s*0*(\d{1,3})\b").unwrap(), "High"),
        (Regex::new(r"(?i)\bep\.?\s*0*(\d{1,3})\b").unwrap(), "Medium"),
        (Regex::new(r"(?i)\bS\d{1,2}E0*(\d{1,3})\b").unwrap(), "Medium"),
        (Regex::new(r"(?i)\bE0*(\d{1,3})\b").unwrap(), "Low"),
        (Regex::new(r"^\s*0*(\d{1,3})\s*[-._]\s*[A-Za-z]").unwrap(), "Low"),
    ]
});

/// Something that reads like an episode marker in a title's name, tried
/// from most to least confidence-inspiring.
pub fn find_episode_hint(text_values: &[String]) -> Option<Hint> {
    for tier in ["High", "Medium", "Low"] {
        for (pattern, conf) in HINT_PATTERNS.iter() {
            if *conf != tier {
                continue;
            }
            for val in text_values {
                if let Some(c) = pattern.captures(val) {
                    if let Ok(ep) = c[1].parse::<i64>() {
                        return Some(Hint { episode: ep, source: val.clone(), confidence: tier.into() });
                    }
                }
            }
        }
    }
    None
}

/// Makes a string safe as a file/folder name on Linux, SMB and Windows.
pub fn safe_filename(name: &str) -> String {
    let replaced: String = name
        .chars()
        .map(|c| if "<>:\"/\\|?*".contains(c) || (c as u32) < 0x20 { ' ' } else { c })
        .collect();
    let collapsed = replaced.split_whitespace().collect::<Vec<_>>().join(" ");
    collapsed.trim_end_matches('.').trim_end().to_string()
}

#[cfg(test)]
pub(crate) mod tests {
    use super::*;

    pub const REAL_SCAN: &str =
        include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/tests/fixtures/kare_kano_vol5_info.txt"));

    #[test]
    fn disc_and_titles() {
        let disc = parse_disc_info(REAL_SCAN);
        assert_eq!(disc.disc_type, "DVD");
        assert_eq!(disc.disc_name, "KARE_KANO_VOL5");
        let d: Vec<i64> = disc.titles.iter().map(|t| t.duration_sec).collect();
        assert_eq!(d, vec![4230, 1387, 1386, 1457, 830, 16]);
        assert_eq!(disc.titles[0].size_bytes, 3395061760);
        assert_eq!(disc.titles[0].chapters, 22);
    }

    #[test]
    fn generated_names_are_not_episode_hints() {
        let disc = parse_disc_info(REAL_SCAN);
        assert!(disc.titles.iter().all(|t| t.text_values().is_empty()));
    }

    #[test]
    fn drives_skip_empty_slots() {
        let drives = parse_drives(REAL_SCAN);
        assert_eq!(drives.len(), 1);
        assert_eq!(drives[0].disc_name, "KARE_KANO_VOL5");
        assert_eq!(drives[0].device, "F:");
    }

    #[test]
    fn messages_keep_umlauts() {
        let disc = parse_disc_info(REAL_SCAN);
        assert!(disc.messages.iter().any(|m| m == "Titel #1 wurde hinzugefügt (27 cell(s), 1:10:30)"));
    }

    #[test]
    fn version() {
        assert_eq!(version_from_output(REAL_SCAN).as_deref(), Some("MakeMKV v2.0.0 win(x64-release)"));
    }

    #[test]
    fn progress_uses_total_field() {
        let f = |v: [&str; 3]| v.iter().map(|s| s.to_string()).collect::<Vec<_>>();
        assert_eq!(parse_progress(&f(["65536", "32768", "65536"])), Some(50.0));
        assert_eq!(parse_progress(&f(["0", "0", "0"])), None);
    }

    #[test]
    fn quoted_fields() {
        assert_eq!(split_fields(r#"1,"a, b","c\"d",3"#), vec!["1", "a, b", "c\"d", "3"]);
    }

    #[test]
    fn hints() {
        let h = find_episode_hint(&["Show Episode 03".into()]).unwrap();
        assert_eq!((h.episode, h.confidence.as_str()), (3, "High"));
        assert!(find_episode_hint(&["E-AC3 5.1".into()]).is_none());
        assert_eq!(find_episode_hint(&["S01E07".into()]).unwrap().episode, 7);
    }

    #[test]
    fn filenames() {
        assert_eq!(safe_filename("Pilot?"), "Pilot");
        assert_eq!(safe_filename("Bonus: Making of"), "Bonus Making of");
        assert_eq!(safe_filename("a/b\\c..."), "a b c");
    }
}
